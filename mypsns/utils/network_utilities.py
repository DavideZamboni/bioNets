def compute_centrality(G: nx.Graph) -> pd.DataFrame:
    '''
    Compute per-node centrality metrics on the weighted graph.

    Metrics computed:
      - degree_centrality:      normalised degree (fraction of other nodes connected)
      - weighted_degree:        sum of edge weights (strength)
      - betweenness_centrality: fraction of shortest paths passing through the node
                                (weighted; uses 1/weight as path length)
      - closeness_centrality:   inverse of mean shortest path length to all reachable nodes
                                (weighted)

    Disconnected nodes receive betweenness = closeness = 0.0.

    - G: weighted residue-interaction graph from build_graph

    Returns a DataFrame indexed by Resindex with columns:
        label, chain, resname, resindex,
        degree_centrality, weighted_degree,
        betweenness_centrality, closeness_centrality
    '''
    if G.number_of_nodes() == 0:
        return pd.DataFrame()

    # For shortest-path metrics, interpret weight as inverse distance
    # so that stronger interactions correspond to shorter effective paths.
    def _inv_weight(u, v, d):
        w = d.get('weight', 1.0)
        return 1.0 / w if w > 0 else np.inf

    degree_c     = nx.degree_centrality(G)
    weighted_deg = dict(G.degree(weight='weight'))
    between_c    = nx.betweenness_centrality(G, weight=_inv_weight, normalized=True)
    close_c      = nx.closeness_centrality(G, distance=_inv_weight)

    rows = []
    for node, data in G.nodes(data=True):
        rows.append({
            'resindex':              node,
            'label':                 data.get('label', str(node)),
            'chain':                 data.get('chain', ''),
            'resname':               data.get('resname', ''),
            'degree_centrality':     round(degree_c.get(node, 0.0),     6),
            'weighted_degree':       round(weighted_deg.get(node, 0.0), 6),
            'betweenness_centrality':round(between_c.get(node, 0.0),    6),
            'closeness_centrality':  round(close_c.get(node, 0.0),      6),
        })

    df = pd.DataFrame(rows).sort_values('resindex').reset_index(drop=True)
    logging.info(
        f'compute_centrality: {len(df)} nodes processed; '
        f'max betweenness={df["betweenness_centrality"].max():.4f}'
    )
    return df

def detect_communities(
    G:       nx.Graph,
    method:  str = 'louvain',
    seed:    int = 42,
    min_members: int = 2,
) -> Tuple[pd.DataFrame, int]:
    '''
    Detect communities in the residue-interaction graph.

    Supported methods
    -----------------
    louvain (default)
        Louvain algorithm (networkx.algorithms.community.louvain_communities).
        Uses edge weights.  Requires networkx ≥ 2.7.

    greedy_modularity
        Clauset–Newman–Moore greedy modularity maximisation.
        Uses edge weights.  Deterministic.

    label_propagation
        Asynchronous label propagation (Raghavan et al. 2007).
        Fast but non-deterministic; seed is passed to networkx.
    
    connected_components:
    - G:      graph from build_graph (isolated nodes are handled gracefully)
    - method: algorithm name (see above)
    - seed:   random seed for stochastic methods
    - min_members: communities with fewer than this many nodes are dissolved;
              their nodes get community = -1 ("solitary", unclustered) and the
              surviving communities are renumbered 0..k-1. Default 2 drops
              singleton communities. Set to 1 (or 0) to keep every community.

    Returns (community_df, n_communities) where community_df has columns:
        resindex, label, chain, resname, community (integer; -1 = solitary).
        n_communities counts only surviving communities (excludes -1).
    '''
    if G.number_of_edges() == 0:
        # no edges → every node is solitary; with min_members>1 none survive
        comm = 0 if (min_members or 0) <= 1 else -1
        logging.warning('detect_communities: graph has no edges – '
                        '%s', 'all nodes in community 0' if comm == 0
                        else 'all nodes solitary (community -1)')
        rows = [
            {'resindex': n, 'label': d.get('label', ''), 'chain': d.get('chain', ''),
             'resname': d.get('resname', ''), 'community': comm}
            for n, d in G.nodes(data=True)
        ]
        return pd.DataFrame(rows), (1 if comm == 0 else 0)

    method = method.lower()

    if method == 'louvain':
        communities = nx.algorithms.community.louvain_communities(
            G, weight='weight', seed=seed
        )
    elif method == 'greedy_modularity':
        communities = nx.algorithms.community.greedy_modularity_communities(
            G, weight='weight'
        )
    elif method == 'label_propagation':
        communities = nx.algorithms.community.asyn_lpa_communities(
            G, weight='weight', seed=seed
        )
    elif method == 'connected_components':
        communities = list(nx.connected_components(G))

    else:
        raise ValueError(
            f"detect_communities: unknown method '{method}'. "
            "Choose from 'louvain', 'greedy_modularity', 'label_propagation', 'connected_components'."
        )

    node_to_community: Dict[int, int] = {}
    for ci, community_set in enumerate(communities):
        for node in community_set:
            node_to_community[node] = ci

    # Dissolve communities smaller than min_members → -1 (solitary) and
    # renumber the survivors to a contiguous 0..k-1 range.
    if min_members and min_members > 1:
        from collections import Counter
        sizes = Counter(node_to_community.values())
        survivors = sorted(c for c, n in sizes.items() if n >= min_members)
        remap = {c: i for i, c in enumerate(survivors)}
        node_to_community = {n: remap.get(c, -1)
                             for n, c in node_to_community.items()}
        n_dissolved = sum(1 for n in sizes.values() if n < min_members)
        if n_dissolved:
            logging.info('detect_communities (%s): dissolved %d communit%s with '
                         '< %d members → solitary (-1)', method, n_dissolved,
                         'y' if n_dissolved == 1 else 'ies', min_members)

    rows = []
    for node, data in G.nodes(data=True):
        rows.append({
            'resindex':  node,
            'label':     data.get('label',   ''),
            'chain':     data.get('chain',   ''),
            'resname':   data.get('resname', ''),
            'community': node_to_community.get(node, -1),
        })

    df = pd.DataFrame(rows).sort_values(['community', 'resindex']).reset_index(drop=True)
    n_communities = int(df.loc[df['community'] >= 0, 'community'].nunique())
    logging.info(
        f'detect_communities ({method}): {n_communities} communities detected'
    )
    return df, n_communities

def shortest_paths(
    G:          nx.Graph,
    source:     Optional[Union[int, List[int]]] = None,
    target:     Optional[Union[int, List[int]]] = None,
) -> pd.DataFrame:
    '''
    Compute weighted shortest paths between residue pairs.

    Path length uses 1/weight (stronger contacts = shorter effective distance).
    When source and target are both None, all-pairs paths are computed (may be
    slow on large graphs).

    - G:      graph from build_graph
    - source: single Resindex or list of Resindices to use as path sources;
              None uses all nodes
    - target: single Resindex or list of Resindices to use as path targets;
              None uses all nodes

    Returns a DataFrame with columns:
        source, target, path_length, path_nodes
    where path_nodes is a comma-separated string of Resindices along the path.
    '''
    def _inv_weight(u, v, d):
        w = d.get('weight', 1.0)
        return 1.0 / w if w > 0 else np.inf

    sources = [source] if isinstance(source, int) else (source or list(G.nodes()))
    targets = [target] if isinstance(target, int) else (target or list(G.nodes()))

    rows = []
    for src in sources:
        if not G.has_node(src):
            continue
        try:
            lengths = nx.single_source_dijkstra_path_length(G, src, weight=_inv_weight)
            paths   = nx.single_source_dijkstra_path(G, src, weight=_inv_weight)
        except nx.NetworkXError:
            continue
        for tgt in targets:
            if tgt == src or tgt not in lengths:
                continue
            rows.append({
                'source':      src,
                'target':      tgt,
                'path_length': round(lengths[tgt], 6),
                'path_nodes':  ','.join(str(n) for n in paths[tgt]),
            })

    df = pd.DataFrame(rows)
    logging.info(f'shortest_paths: {len(df)} source–target pairs computed')
    return df

