# for HC/SB contacts
def load_pair_contacts(
    csv_paths:  List[Path],
    int_df:     pd.DataFrame,
    n_frames:   int,
) -> pd.DataFrame:
    '''
    Load SB or HC merged CSVs and return a per-residue-pair frequency table.

    Each CSV has columns: frame, id_1, id_2, distance.
    The id labels encode the residue index as the suffix _r{Resindex}.
    Contact frequency is defined as:

        frequency(u, v) = (# distinct frames in which u–v contact appears) / n_frames

    - csv_paths: list of *_merged.csv paths (one per chain-pair computation)
    - int_df:    whole_topology_interactors DataFrame (for node-label look-up)
    - n_frames:  total number of trajectory frames analysed

    Returns a DataFrame with columns:
        res_1, res_2, chain_1, chain_2, label_1, label_2, frequency, mean_dist
    where res_1 < res_2 (canonical ordering).
    '''
    empty = pd.DataFrame(columns=[
        'res_1', 'res_2', 'chain_1', 'chain_2',
        'label_1', 'label_2', 'frequency', 'mean_dist',
    ])

    if not csv_paths:
        return empty

    chunks = []
    for p in csv_paths:
        df = pd.read_csv(p, header=0, index_col=False)
        if not _SCHEMA_PAIR.issubset(df.columns):
            logging.warning(f'load_pair_contacts: unexpected columns in {p.name} – skipped')
            continue
        df = df.dropna(subset=['id_1', 'id_2'])
        df['res_1'] = df['id_1'].astype(str).apply(resindex_from_id)
        df['res_2'] = df['id_2'].astype(str).apply(resindex_from_id)
        chunks.append(df[['frame', 'res_1', 'res_2', 'distance']])

    if not chunks:
        return empty

    raw = pd.concat(chunks, ignore_index=True)

    # Canonical ordering: smaller resindex first
    swap = raw['res_1'] > raw['res_2']
    raw.loc[swap, ['res_1', 'res_2']] = raw.loc[swap, ['res_2', 'res_1']].values

    agg = (
        raw.groupby(['res_1', 'res_2'])
           .agg( # aggregate (pandas.core.groupby.DataFrameGroupBy.aggregate )
               n_frames_contact=pd.NamedAgg(column='frame', aggfunc=lambda x: len(np.unique(x))), # count unique frames
               mean_dist=pd.NamedAgg(column='distance', aggfunc=lambda x: np.mean(x)) # mean_dist
           )
           .reset_index()
    )
    agg['frequency'] = agg['n_frames_contact'] / n_frames

    # get matrix.dat data

    # Attach chain and label info from whole_topology_interactors
    label_map = build_label_map(int_df)
    chain_map = build_chain_map(int_df)

    agg['chain_1'] = agg['res_1'].map(chain_map)
    agg['chain_2'] = agg['res_2'].map(chain_map)
    agg['label_1'] = agg['res_1'].map(label_map)
    agg['label_2'] = agg['res_2'].map(label_map)

    return agg[['res_1', 'res_2', 'chain_1', 'chain_2',
                'label_1', 'label_2', 'frequency', 'mean_dist']]

# for Hbonds
def load_hbond_contacts(
    csv_paths: List[Path],
    int_df:    pd.DataFrame,
    n_frames:  int,
) -> pd.DataFrame:
    '''
    Load H-bond merged CSVs and return a per-residue-pair frequency table.

    Each CSV has columns: Frame, Donor_ix, Hydrogen_ix, Acceptor_ix, Distance.
    Donor_ix and Acceptor_ix are MDAnalysis atom indices that match the
    'atom_index' column of whole_topology_interactors.  The H atom
    (Hydrogen_ix) is excluded from the residue-pair identification.

    Contact frequency is defined as:

        frequency(u, v) = (# distinct frames with ≥1 u–v H-bond) / n_frames

    - csv_paths: list of *_merged.csv paths
    - int_df:    whole_topology_interactors DataFrame
    - n_frames:  total number of trajectory frames analysed

    Returns a DataFrame with the same columns as load_pair_contacts.
    '''
    empty = pd.DataFrame(columns=[
        'res_1', 'res_2', 'chain_1', 'chain_2',
        'label_1', 'label_2', 'frequency', 'mean_dist',
    ])

    if not csv_paths:
        return empty

    # Build atom_index → Resindex map from whole_topology_interactors
    ix_to_res: Dict[int, int] = dict(
        zip(int_df['atom_index'].astype(int).tolist(),
            int_df['Resindex'].astype(int).tolist())
    )

    chunks = []
    for p in csv_paths:
        df = pd.read_csv(p, header=0, index_col=False)
        if not _SCHEMA_HBOND.issubset(df.columns):
            logging.warning(f'load_hbond_contacts: unexpected columns in {p.name} – skipped')
            continue
        df = df.dropna(subset=['Donor_ix', 'Acceptor_ix'])
        df['res_1'] = df['Donor_ix'].astype(int).map(ix_to_res)
        df['res_2'] = df['Acceptor_ix'].astype(int).map(ix_to_res)
        df = df.dropna(subset=['res_1', 'res_2'])
        df['res_1'] = df['res_1'].astype(int)
        df['res_2'] = df['res_2'].astype(int)
        chunks.append(df[['Frame', 'res_1', 'res_2', 'Distance']].rename(
            columns={'Frame': 'frame', 'Distance': 'distance'}
        ))

    if not chunks:
        return empty

    raw = pd.concat(chunks, ignore_index=True)

    # Canonical ordering
    swap = raw['res_1'] > raw['res_2']
    raw.loc[swap, ['res_1', 'res_2']] = raw.loc[swap, ['res_2', 'res_1']].values

    # Drop self-contacts (donor and acceptor in same residue)
    raw = raw[raw['res_1'] != raw['res_2']]

    agg = (
        raw.groupby(['res_1', 'res_2'])
           .agg( # aggregate (pandas.core.groupby.DataFrameGroupBy.aggregate)
               n_frames_contact=pd.NamedAgg(column='frame', aggfunc=lambda x: len(np.unique(x))), # count unique frames
               mean_dist=pd.NamedAgg(column='distance', aggfunc=lambda x: np.mean(x)) # mean_dist
           )
           .reset_index()
    )
    agg['frequency'] = agg['n_frames_contact'] / n_frames

    label_map = build_label_map(int_df)
    chain_map = build_chain_map(int_df)

    agg['chain_1'] = agg['res_1'].map(chain_map)
    agg['chain_2'] = agg['res_2'].map(chain_map)
    agg['label_1'] = agg['res_1'].map(label_map)
    agg['label_2'] = agg['res_2'].map(label_map)

    return agg[['res_1', 'res_2', 'chain_1', 'chain_2',
                'label_1', 'label_2', 'frequency', 'mean_dist']]

