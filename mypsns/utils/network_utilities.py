def build_resindex_to_pdb_map(topology_pdb) -> dict:
    """
    Re-read the topology with MDAnalysis and return
    ``{Resindex (int): (chain_id (str), pdb_resid (int), anchor (str | None))}``.

    PyMOL selects residues by ``chain X and resi N`` where ``N`` is the PDB
    residue number — *not* MDAnalysis' global ``Resindex``.  The map lets the
    PyMOL writer emit correct selectors regardless of multi-chain offsets,
    insertion codes, or non-contiguous numbering.

    ``anchor`` is the atom name to render the residue's node / edge endpoint on,
    chosen so that non-protein residues (ions, lipids, nucleic acids, sugars)
    also display:

      * ``'CA'``           if the residue has a CA atom (standard amino acids);
      * the lone atom name  if the residue is monoatomic (e.g. a CAL/NA/CL ion);
      * ``None``            otherwise (multi-atom residue with no CA — lipids,
                            nucleotides, carbohydrates). The writer then renders
                            a pseudoatom at the residue's center of mass.

    Falls back to an empty dict if MDAnalysis can't open the file.
    """
    import logging
    from pathlib import Path
    try:
        import MDAnalysis as mda
    except ImportError:
        logging.warning('build_resindex_to_pdb_map: MDAnalysis unavailable; '
                        'PyMOL selectors will fall back to Resindex.')
        return {}
 
    try:
        u = mda.Universe(str(Path(topology_pdb)))
    except Exception as e:
        logging.warning('build_resindex_to_pdb_map: cannot load %s (%s)',
                        topology_pdb, e)
        return {}
 
    out: dict = {}
    n_ca = n_single = n_com = 0
    for res in u.residues:
        # chainID is the PDB chain; fall back to segid (GROMACS-style)
        chain = ''
        try:
            for a in res.atoms:
                cid = getattr(a, 'chainID', None)
                if cid:
                    chain = str(cid).strip()
                    break
        except Exception:
            pass
        if not chain and getattr(res, 'segid', ''):
            chain = str(res.segid).strip()
        try:
            resnum = int(res.resnum)
        except Exception:
            continue

        # ── anchor-atom selection ────────────────────────────────────────────
        try:
            names = [str(n) for n in res.atoms.names]
        except Exception:
            names = []
        if 'CA' in names:
            anchor = 'CA'
            n_ca += 1
        elif len(names) == 1:
            anchor = names[0]          # monoatomic ion
            n_single += 1
        else:
            anchor = None              # multi-atom, no CA → center of mass
            n_com += 1

        out[int(res.resindex)] = (chain, resnum, anchor)
 
    logging.info('build_resindex_to_pdb_map: %d residues mapped from %s '
                 '(%d CA, %d single-atom, %d center-of-mass)',
                 len(out), topology_pdb, n_ca, n_single, n_com)
    return out

def find_merged_csvs(
    adjacency_root: Path,
    inttype_folder: str,
    target:         str,
) -> List[Path]:
    '''
    Discover all *_merged.csv files for one interaction type under adjacency_root.

    - adjacency_root: e.g. outpath/Adjacency/q_interactors/
    - inttype_folder: sub-folder name, one of 'Salt_bridges', 'H_bonds', 'HCs'
    - target:         human label for log messages (e.g. 'Salt_bridges')

    Returns a sorted list of Path objects (may be empty).
    '''
    folder = adjacency_root / inttype_folder
    if not folder.exists():
        logging.warning(f'find_merged_csvs: folder not found: {folder}')
        return []
    found = sorted(
        f for f in folder.iterdir()
        if f.is_file() and f.name.endswith('_merged.csv')
    )
    logging.info(f'{target}: found {len(found)} merged CSV(s) in {folder}')
    return found

# matrix.dat writer
def write_adjacency_matrices(
    contact_tables: Dict[str, pd.DataFrame],
    int_df:         pd.DataFrame,
    outpath:        Path,
    residue_filter: Optional[List[int]] = None,
    scale:          float = 100.0,
    fmt:            str   = '%.2f',
) -> Dict[str, Path]:
    """
    Write one adjacency matrix .dat file per interaction type, plus a shared
    labels file.
 
    Each .dat is a square symmetric matrix (space-separated) where entry (i,j)
    is  frequency(res_i, res_j) * scale.  Rows/columns are ordered by Resindex.
 
    Parameters
    ----------
    contact_tables : dict
        {inttype_label: frequency_DataFrame} — output of load_pair_contacts /
        load_hbond_contacts, with columns res_1, res_2, frequency.
    int_df : pd.DataFrame
        whole_topology_interactors table (for residue list and labels).
    outpath : Path
        Destination folder for .dat and labels files.
    residue_filter : list[int], optional
        Subset of Resindices to include.  None = all residues in int_df.
    scale : float
        Multiply raw frequency by this before writing (default 100 → percent).
    fmt : str
        Format string for numpy.savetxt (default '%.2f').
 
    Returns
    -------
    dict
        {inttype_label: Path} for each written .dat file, plus 'labels' key.
    """
    # ── Build ordered residue list ───────────────────────────────────────────
    all_resindices = sorted(int_df['Resindex'].unique().astype(int))
    if residue_filter is not None:
        all_resindices = sorted(r for r in all_resindices if r in residue_filter)
 
    n = len(all_resindices)
    idx_map = {r: i for i, r in enumerate(all_resindices)}
 
    # ── Write labels file ────────────────────────────────────────────────────
    label_map = build_label_map(int_df)
    labels_path = outpath / 'adjacency_labels.dat'
    with open(labels_path, 'w') as f:
        for r in all_resindices:
            f.write(f'{r}\t{label_map.get(r, str(r))}\n')
 
    written: Dict[str, Path] = {'labels': labels_path}
 
    # ── One matrix per interaction type ──────────────────────────────────────
    for inttype, table in contact_tables.items():
        mat = np.zeros((n, n), dtype=float)
 
        for _, row in table.iterrows():
            r1, r2 = int(row['res_1']), int(row['res_2'])
            if r1 not in idx_map or r2 not in idx_map:
                continue
            i, j = idx_map[r1], idx_map[r2]
            val  = float(row['frequency']) * scale
            mat[i, j] = val
            mat[j, i] = val  # symmetric
 
        dat_path = outpath / f'{inttype}_adjacency.dat'
        np.savetxt(dat_path, mat, fmt=fmt, delimiter=' ')
        written[inttype] = dat_path
 
        logging.info(
            f'write_adjacency_matrices: {inttype} → {dat_path.name} '
            f'({n}×{n}, {np.count_nonzero(mat)//2} non-zero pairs)'
        )
 
    # ── Also write a combined (summed) matrix ────────────────────────────────
    combined = np.zeros((n, n), dtype=float)
    for inttype, table in contact_tables.items():
        for _, row in table.iterrows():
            r1, r2 = int(row['res_1']), int(row['res_2'])
            if r1 not in idx_map or r2 not in idx_map:
                continue
            i, j = idx_map[r1], idx_map[r2]
            val  = float(row['frequency']) * scale
            combined[i, j] += val
            combined[j, i] += val
 
    combined_path = outpath / 'combined_adjacency.dat'
    np.savetxt(combined_path, combined, fmt=fmt, delimiter=' ')
    written['combined'] = combined_path
    logging.info(
        f'write_adjacency_matrices: combined → {combined_path.name} '
        f'({n}×{n}, {np.count_nonzero(combined)//2} non-zero pairs)'
    )
    return written

