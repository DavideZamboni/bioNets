# GRAPH – build weighted NetworkX graphs
# ═══════════════════════════════════════════════════════════════════════════════

def build_graph(
    contact_tables: Dict[str, pd.DataFrame],
    int_df:         pd.DataFrame,
    min_frequency:  float = 0.0,
) -> nx.Graph:
    '''
    Build a weighted, undirected residue-interaction graph.

    Nodes represent residues (identified by their Resindex).  An edge is
    drawn between two residues when they share at least one contact type with
    frequency ≥ min_frequency.  Multiple contact types between the same pair
    are combined by summing their frequencies.

    Node attributes added from whole_topology_interactors:
      - label:    Chain:resname:Resindex  (e.g. 'A:ALA:42')
      - chain:    chain identifier
      - resname:  resname
      - resindex: Resindex (integer)

    Edge attributes:
      - weight:    summed contact frequency across all active contact types
      - mean_dist: frequency-weighted mean distance across contact types
      - <inttype>_freq: per-type frequency (e.g. 'SB_freq', 'HB_freq', 'HC_freq')

    - contact_tables: {type_label: frequency_DataFrame} from load_*_contacts
    - int_df:         whole_topology_interactors DataFrame
    - min_frequency:  edges with total weight below this value are excluded;
                      default 0.0 includes all observed contacts

    Returns a nx.Graph with node and edge attributes populated.
    '''
    G = nx.Graph()

    # ── Add all residues as nodes ─────────────────────────────────────────────
    label_map   = build_label_map(int_df)
    chain_map   = build_chain_map(int_df)
    resname_map = dict(zip(
        int_df.drop_duplicates('Resindex')['Resindex'].astype(int),
        int_df.drop_duplicates('Resindex')['resname'],
    ))

    for resix, label in label_map.items():
        G.add_node(
            resix,
            label    = label,
            chain    = chain_map.get(resix, ''),
            resname  = resname_map.get(resix, ''),
            resindex = resix,
        )

    # ── Add edges from each contact type ─────────────────────────────────────
    for inttype, table in contact_tables.items():
        if table.empty:
            continue
        freq_col = f'{inttype}_freq'
        for _, row in table.iterrows():
            u, v  = int(row['res_1']), int(row['res_2'])
            freq  = float(row['frequency'])
            dist  = float(row['mean_dist'])

            if not G.has_node(u) or not G.has_node(v):
                continue

            if G.has_edge(u, v):
                G[u][v]['weight']    += freq
                # Update frequency-weighted mean distance
                old_w   = G[u][v]['weight'] - freq
                old_d   = G[u][v]['mean_dist']
                G[u][v]['mean_dist'] = (old_w * old_d + freq * dist) / G[u][v]['weight']
            else:
                G.add_edge(u, v, weight=freq, mean_dist=dist)

            G[u][v][freq_col] = freq

    # ── Apply frequency threshold ─────────────────────────────────────────────
    if min_frequency > 0.0:
        to_remove = [
            (u, v) for u, v, d in G.edges(data=True)
            if d.get('weight', 0.0) < min_frequency
        ]
        G.remove_edges_from(to_remove)
        logging.info(
            f'build_graph: removed {len(to_remove)} edges below '
            f'frequency threshold {min_frequency:.3f}'
        )

    logging.info(
        f'build_graph: {G.number_of_nodes()} nodes, '
        f'{G.number_of_edges()} edges'
    )
    return G

