def filter_by_weight(G: nx.Graph, min_weight: float) -> nx.Graph:
    '''
    Return a copy of G with all edges below min_weight removed.

    Isolated nodes (degree 0 after filtering) are retained in the graph but
    will not appear in edge-based analyses.

    - G:          source graph
    - min_weight: edges with weight strictly below this value are removed

    Returns a new nx.Graph.
    '''
    H = G.copy()
    to_remove = [
        (u, v) for u, v, d in H.edges(data=True)
        if d.get('weight', 0.0) < min_weight
    ]
    H.remove_edges_from(to_remove)
    logging.info(
        f'filter_by_weight({min_weight:.3f}): '
        f'removed {len(to_remove)} edges, '
        f'{H.number_of_edges()} remain'
    )
    return H

def filter_by_degree(G: nx.Graph, min_degree: int) -> nx.Graph:
    '''
    Return a copy of G with all nodes below min_degree (and their edges) removed.

    - G:          source graph
    - min_degree: nodes with degree strictly below this value are removed

    Returns a new nx.Graph.
    '''
    H = G.copy()
    to_remove = [n for n, deg in H.degree() if deg < min_degree]
    H.remove_nodes_from(to_remove)
    logging.info(
        f'filter_by_degree({min_degree}): '
        f'removed {len(to_remove)} nodes, '
        f'{H.number_of_nodes()} remain'
    )
    return H

